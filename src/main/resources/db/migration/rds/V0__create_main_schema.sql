-- 메인 RDS(main datasource) 스키마 전체 생성.
--
-- 기존에는 이 스키마를 JPA(hibernate ddl-auto=update)가 애플리케이션 기동 시점에
-- 엔티티로부터 자동 생성했고, Flyway는 데이터 INSERT/스키마 보정만 담당했다.
-- 문제는 Spring Boot 기동 순서상 Flyway가 Hibernate보다 먼저(혹은 더 이르게) 실행될
-- 수 있어서, 테이블이 하나도 없는 새 환경(다른 컴퓨터/새 DB)에서 clone 후 최초 실행하면
-- V1 이하 마이그레이션이 "테이블이 아직 없다"며 실패하거나(예: 과거 V12) 조용히
-- no-op(IF EXISTS 가드)로 넘어가 버려서 정작 스키마가 전혀 만들어지지 않았다.
--
-- 이 마이그레이션은 그 근본 원인을 없애기 위해, 엔티티가 정의하는 테이블 구조를
-- Flyway 코드로 명시한다. 이후 ddl-auto는 validate로 바꿔서 Hibernate는 스키마를
-- "만들지" 않고 엔티티와 일치하는지 검증만 하도록 한다.
--
-- 여기서 만드는 스키마는 "V1이 실행되기 직전 시점"의 형태다. V3/V5/V6/V8/V9/V10/V11/
-- V12/V13/V15/V16이 그 뒤에서 원래 의도대로 컬럼 추가/제약조건 추가/타입 변경을
-- 순서대로 적용해서 최종적으로 지금의 엔티티와 같은 모습이 된다. (즉 여기서 그 뒤
-- 마이그레이션이 추가하는 컬럼/제약조건을 미리 넣지 않는다 - 특히 V12처럼 IF NOT EXISTS
-- 가드가 없는 ADD COLUMN이 있으면 중복 생성으로 실패하기 때문.)

